#!/usr/bin/env python3
"""Generate the Chart Beyond variant of the Multi-Session ORB Pro indicator.

Chart Beyond (chartbeyond.com) runs a subset of Pine Script. Its editor reported
"17 of 20 features supported. Not yet: alert, table +1". This script copies
MultiSessionORBPro.pine and swaps only the blocks marked `TV …` (TradingView-only code):

    TV ALERT INPUTS      alert inputs           → constants (alerts disabled)
    TV ALERTS            alert() calls          → no-op
    TV DASHBOARD         table dashboard        → one multi-line label
    TV ALERTCONDITIONS   alertcondition() calls → removed

Everything else — inputs, session clock, range builder, signal engine, drawings — is
copied unchanged, so the variant cannot drift from the TradingView version.

Usage:
    python3 pine/tools/make_chartbeyond.py           # (re)write MultiSessionORBPro_ChartBeyond.pine
    python3 pine/tools/make_chartbeyond.py --check   # exit 1 if the file is out of date
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "MultiSessionORBPro.pine"
TARGET = ROOT / "MultiSessionORBPro_ChartBeyond.pine"

REPLACEMENTS = {
    "TV ALERT INPUTS": '''// ───────────────────────────── ⑫ Alerts ─────────────────────────────
// Chart Beyond has no alert() support yet: the alert settings are fixed so the shared code compiles.
// Use the TradingView version of this indicator for alerts / webhooks.
string alFmt    = "Text"
string alBot    = "AutoKel"
bool   alBreak  = false
bool   alRetest = false
bool   alSetup  = false
bool   alFalse  = false
bool   alExit   = false
''',
    "TV ALERTS": '''// No alert() on this platform: alert events are not sent (signals are still drawn).
f_alerts(SessCfg c, SessState s) =>
    true
''',
    "TV DASHBOARD": '''// ───────────────────────────── Dashboard (label — this platform has no tables) ─────────────────────────────
int dbOffset = input.int(30, "Dashboard offset (bars right of the last bar)", minval = 0, maxval = 400, group = G_DB, display = display.none)
var label dashLbl = na
if barstate.islast
    f_delX(dashLbl)
    dashLbl := na
    if dbOn
        string txt = f_titleTxt()
        for i = 0 to 3
            SessCfg c = A_CFG.get(i)
            SessState s = A_ST.get(i)
            int shown = f_shownStart(c, s, A_DR.get(i))
            int dr = f_dirOf(s)
            txt := txt + "\\n" + f_sessName(c) + ": " + f_statusFull(c, s, shown) + (dr > 0 ? " · Bull" : dr < 0 ? " · Bear" : "") + (c.enabled ? " · range " + f_rangeTxt(s) : "")
            if dbValid and c.enabled
                txt := txt + " · NY " + f_when(shown, "America/New_York") + " · UTC " + f_when(shown, "GMT+0")
        int curIdx = f_currentIdx(A_CFG, A_ST)
        if curIdx >= 0
            txt := txt + "\\n" + f_currentTxt(A_CFG.get(curIdx), A_ST.get(curIdx)) + "\\n" + f_currentRange(A_CFG.get(curIdx), A_ST.get(curIdx))
        else
            txt := txt + "\\nCurrent: none active"
        txt := txt + "\\n" + f_modeTxt()
        if dbBias
            txt := txt + "\\n" + f_biasTxt()
        string w = f_warnings()
        if w != ""
            txt := txt + "\\n" + w
        dashLbl := label.new(time + dbOffset * TF_SEC * 1000, sC, txt, xloc = xloc.bar_time, style = label.style_label_left, color = color.new(#131722, 10), textcolor = cTxt, size = DB_SIZE)
''',
    "TV ALERTCONDITIONS": '''// alertcondition() is not available on this platform.
''',
}

HEADER_NOTE = (
    "// GENERATED by pine/tools/make_chartbeyond.py from MultiSessionORBPro.pine — edit the source\n"
    "// file and re-run the generator instead of editing this file.\n"
    "// Chart Beyond variant: no alert() / alertcondition() / table (not supported there yet);\n"
    "// the dashboard is drawn as a label. Signals and drawings are identical to the TradingView version.\n"
)


def build() -> str:
    src = SOURCE.read_text(encoding="utf-8")
    out = src
    for name, body in REPLACEMENTS.items():
        pat = re.compile(rf"^// ╔═+ BEGIN {name} ═+╗\n.*?^// ╔═+ END {name} ═+╗\n", re.M | re.S)
        if len(pat.findall(out)) != 1:
            raise SystemExit(f"block '{name}' not found exactly once in {SOURCE.name}")
        cb_name = name.replace("TV ", "CHART BEYOND ")
        pad = "═" * max(3, (60 - len(cb_name)) // 2)
        block = f"// ╔{pad} BEGIN {cb_name} {pad}╗\n{body}// ╔{pad} END {cb_name} {pad}╗\n"
        out = pat.sub(lambda _m: block, out)
    title_old = 'indicator("Multi-Session ORB Pro", shorttitle = "MS-ORB Pro",'
    title_new = 'indicator("Multi-Session ORB Pro (Chart Beyond)", shorttitle = "MS-ORB Pro CB",'
    if out.count(title_old) != 1:
        raise SystemExit("indicator() declaration not found")
    out = out.replace(title_old, title_new)
    first_nl = out.index("\n") + 1  # keep //@version=6 as the first line
    return out[:first_nl] + HEADER_NOTE + out[first_nl:]


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print(f"FAIL {TARGET.name} is out of date: run python3 pine/tools/make_chartbeyond.py")
            return 1
        print(f"OK  {TARGET.name} is up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.name} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
